    private void bSamaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bSamaActionPerformed
        // koding untuk tombol =
        switch(pilih) {
            case 1:
                bil2 = Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah = bil1+bil2;
                bil = Double.toString(jumlah);
                break;
            case 2:
                bil2 = Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah = bil1-bil2;
                bil = Double.toString(jumlah);
                break;
            case 3:
                bil2 = Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah = bil1*bil2;
                bil = Double.toString(jumlah);
                break;
            case 4:
                bil2 = Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah = bil1/bil2;
                bil = Double.toString(jumlah);
                break;
        }
        
        if(jumlah % 1 == 0) {
            txtTampil.setText(String.valueOf((int) jumlah));
        } else {
            txtTampil.setText(String.valueOf(jumlah));            
        }
    }//GEN-LAST:event_bSamaActionPerformed

